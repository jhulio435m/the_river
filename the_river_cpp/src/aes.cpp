std::string AESHelper::Decrypt(const std::string& cipherText, const std::string& key, const std::string& iv) {
    std::vector<byte> decoded = base64_decode(cipherText);
    if(decoded.empty()) return cipherText;
    
    std::string decrypted;
    for(size_t i=0; i<decoded.size(); ++i) {
        decrypted += (char)(decoded[i] ^ (byte)key[i % key.length()]);
    }
    
    // Remove PKCS7 padding
    if(!decrypted.empty()) {
        int pad = (int)decrypted.back();
        if(pad > 0 && pad <= 16) {
            bool valid = true;
            for(int i=0; i<pad; ++i) {
                if(decrypted[decrypted.length()-1-i] != pad) { valid = false; break; }
            }
            if(valid) decrypted = decrypted.substr(0, decrypted.length() - pad);
        }
    }
    
    return decrypted;
}
